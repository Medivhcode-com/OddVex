def test_no_name_in_the_sample_data_and_no_example_prompt_matches_a_rule(
    provider: SyntheticProvider,
) -> None:
    """A team, player or sportsbook name must never be read as distress or as an age."""
    teams = provider.list_teams()
    names = [
        *(team.name for team in teams),
        *(team.nickname for team in teams),
        *(team.city for team in teams),
        *(team.abbreviation for team in teams),
        *(player.name for player in provider.list_players()),
        *(book.name for book in provider.list_sportsbooks()),
    ]
    assert len(names) > 200
    prompts = [
        "Who has the best price on the {name}?",
        "How has {name} done on passing yards lately?",
        "{name} points last 10",
        "line movement for {name}",
        # The sports talk the rules have exceptions for, with every name in it.
        "can the {name} win it back in game 7",
        "the {name} can't stop anyone",
        "I think the {name} are dead in the water",
        "are the {name} still alive in the playoffs",
        "I'm 3-1 on the {name} this month",
        "I lost my last bet on the {name}",
        "I'm 20 bucks down on the {name}",
        "I wish I had taken the {name}",
        "I'm going to bet the {name}",
        "I just want the {name} price",
    ]
    for name in names:
        assert detect(name) == Signals(), name
        for prompt in prompts:
            assert detect(prompt.format(name=name)) == Signals(), (prompt, name)
    # The examples the web and mobile assistants offer on an empty chat.
    for example in (
        "What is expected value?",
        "How do you remove the vig?",
        "How are my bets doing?",
    ):
        assert detect(example) == Signals(), example


