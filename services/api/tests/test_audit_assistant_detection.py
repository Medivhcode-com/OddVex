# ------------------------------------------------------------------- the wording
REPLIES = {
    "crisis": safeguards.reply(Signals(crisis=True)),
    "underage": safeguards.reply(Signals(underage=True)),
    "underage and distress": safeguards.reply(Signals(underage=True, distress=True)),
    "distress": safeguards.reply(Signals(distress=True)),
    "chasing losses": safeguards.reply(Signals(distress=True, chasing_losses=True)),
    "certainty": safeguards.NO_CERTAINTY_REPLY,
}


@pytest.mark.parametrize("name", REPLIES)
def test_reply_wording_follows_the_copy_rules(name: str) -> None:
    text = REPLIES[name]
    lowered = text.lower()
    for phrase in (
        # PROJECT_CONSTITUTION.md and BRAND_VOICE.md: never, anywhere.
        "lock",
        "guarantee",
        "can't lose",
        "risk-free",
        "risk free",
        "sure thing",
        "win either way",
        # Nothing that blames, diagnoses or orders.
        "your fault",
        "irresponsible",
        "reckless",
        "stupid",
        "foolish",
        "should have",
        "shame",
        "addict",
        "you must",
        "you need to",
        "you have a problem",
        # Nothing that sells or hurries.
        "premium",
        "upgrade",
        "hurry",
        "act now",
        "best bet",
    ):
        assert phrase not in lowered, (name, phrase)
    assert "!" not in text and text == text.strip() and "  " not in text
    assert all(paragraph.endswith(".") for paragraph in text.split("\n\n")), name


