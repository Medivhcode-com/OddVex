def test_which_case_wins_when_several_match() -> None:
    assert Signals().case is None
    assert Signals(certainty=True).case is None
    assert Signals(distress=True, chasing_losses=True, certainty=True).case == "distress"
    assert Signals(underage=True, distress=True).case == "underage"
    assert Signals(crisis=True, underage=True, distress=True, certainty=True).case == "crisis"
    both = detect("I'm 19 and I lost everything")
    assert both.underage and both.distress and both.case == "underage"
    worst = detect("I'm 17, I can't stop betting and I want to die. Any locks?")
    assert worst == Signals(crisis=True, underage=True, distress=True, certainty=True)


def test_spelling_of_apostrophes_spaces_and_case_does_not_matter() -> None:
    assert normalise("  I  CAN\u2019T\tstop\n") == "i cant stop"
    assert normalise("I can't stop") == normalise("i cant stop") == normalise("I can`t stop")
    assert normalise("I\u2019m only 20 \u2014 line movement") == "im only 20 - line movement"
    full_width = "\uff4b\uff49\uff4c\uff4c \uff4d\uff59\uff53\uff45\uff4c\uff46"
    assert normalise(full_width) == "kill myself"
    assert normalise("kill my\u200bself") == "kill myself"  # zero-width space
    for message in (
        "I can\u2019t stop betting",
        "I CAN'T STOP BETTING",
        "i cant   stop betting",
        "I cannot stop betting",
        "I can not stop betting",
    ):
        assert detect(message).distress, message
    for message in ("I\u2019m 17", "IM 17", "i  am 17", "I'M SEVENTEEN"):
        assert detect(message).underage, message


