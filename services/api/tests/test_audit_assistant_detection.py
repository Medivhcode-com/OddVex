def test_a_birth_year_is_read_against_the_date() -> None:
    today = date(2026, 11, 19)
    for message in (
        "I was born in 2009",
        "i was born in 2008, best odds on the Tides",
        "I was born on March 3, 2010",
        "I was born in 2006",  # twenty at the latest
    ):
        assert detect(message, today).case == "underage", message
    for message in (
        "I was born in 2005",  # twenty or twenty-one: not known, so not treated as under 21
        "I was born in 1990",
        "I was born in Boston",
        "I was born in 2020",  # nobody that young is typing here
        "he was born in 2009",
        "the rookie was born in 2008",
    ):
        assert detect(message, today) == Signals(), message
